import assert from 'node:assert/strict';
import fs from 'node:fs';
import { advanceHeroLogo } from '../src/animation/hero-logo.js';
const state = { angle: 0, entryAngle: null };
advanceHeroLogo(state, 800, 350, 0, 1 / 60);
assert.ok(state.angle > 0, 'Hero still rotates before arrival');
const before = state.angle;
advanceHeroLogo(state, 175, 350, 0, 1 / 60);
assert.ok(state.angle > before, 'Logo settles during approach');
const stopped = advanceHeroLogo(state, 0, 350, 0, 1 / 60);
assert.equal(stopped, Math.PI * 2);
for (let i = 0; i < 600; i++) assert.equal(advanceHeroLogo(state, -100, 350, 20, 1 / 60), stopped);
advanceHeroLogo(state, 800, 350, 0, 1 / 60);
assert.ok(state.angle > stopped, 'Reverse scroll restores the hero entry');
const source = fs.readFileSync('src/pages/HomePage.jsx', 'utf8');
assert.ok(source.includes('<Services circleRef={circleRef} />'));
assert.ok(source.includes('o.current += i * (0.5 + a)'), 'Original footer spin restored');
assert.ok(!source.includes('footerLogoPose'));
console.log('PASS: hero arrival, stable docked pose despite velocity, reverse scroll, original footer rotation.');
